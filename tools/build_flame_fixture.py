"""Rebuild the flame demonstration and reader digests from our synthetic frames.

The reference layout, its burner linked to the run's `volumes.csv`, and a
`reconstructedFlame` linking the run's `voxels/` folder with the manifest the
Python reader computes. `web/src/core/flame.test.ts` and `python/tests/test_flame.py`
hold both engines to this file byte for byte.
"""
import gzip
import hashlib
import io
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'python'))
from fireplan import Plan
from fireplan.flame import FlameSequence
from fireplan.linked_files import parse_reconstruction_csv

IMPORTED_AT = '2026-09-19T20:00:00Z'


def main():
    data = json.loads((ROOT / 'fixtures/pool-fire-camera-row.ftp.json').read_text(encoding='utf-8'))
    data['meta']['title'] = 'Synthetic flame demonstration'
    data['meta']['notes'] = ('A synthetic 80 kW heptane design fire on the reference layout\'s 1 ft square pan, '
                             'generated by tools/build_synthetic_flame.py: 80 voxel frames at 5 s in voxels/, '
                             'with volumes.csv computed from those frames. The rig frame is the plan frame. '
                             'Illustrative synthetic data, not a recorded test; linked data changes no prediction or verdict.')
    plot = parse_reconstruction_csv((ROOT / 'fixtures/flame/volumes.csv').read_text(encoding='utf-8'),
                                    imported_at=IMPORTED_AT)
    for obj in data['objects']:
        if obj['id'] == 'burner-main':
            # The specified synthetic design fire, independent of the CSV descriptors.
            obj['fire']['hrr_kw'] = 80.0
            obj['linkedFiles'] = [{'id': 'volumes', 'kind': 'spreadsheet', 'path': 'volumes.csv',
                                   'label': 'Synthetic flame volumes', 'plot': plot}]
    plan = Plan(data)
    plan.add_reconstructed_flame('voxels', str(ROOT / 'fixtures/flame/voxels'),
                                 object_id='flame-main', name='Synthetic flame', burner_id='burner-main',
                                 label='Synthetic flame frames', imported_at=IMPORTED_AT)
    plan.validate_schema()
    assert not [i for i in plan.check() if i.code.startswith('flame-')], plan.check()
    plan.save(ROOT / 'fixtures/flame/flame-test.ftp.json', update_modified=False)
    # The packed frames, gzipped: what the bundled Example and a shared page carry.
    # gzip is the transport; the packed stream inside is the canonical, engine-
    # identical form the tests pin.
    sequence = FlameSequence.load(str(ROOT / 'fixtures/flame/voxels'))
    packed = sequence.pack()
    compressed = io.BytesIO()
    # Fix the OS header byte as well as mtime, independently of Python version.
    with gzip.GzipFile(filename='', mode='wb', fileobj=compressed, mtime=0) as stream:
        stream.write(packed)
    (ROOT / 'fixtures/flame/flame-test.fvs').write_bytes(compressed.getvalue())
    surface_digest = hashlib.sha256()
    counts = []
    for frame in sequence.frames:
        cells = frame.surface_cells().astype('<u2')
        counts.append(len(cells))
        surface_digest.update(cells.tobytes())
    expected = {
        'note': 'Written by tools/build_flame_fixture.py using python/fireplan/flame.py on the synthetic fixture; web/src/core/flame.test.ts holds the TypeScript reader to it.',
        'manifest': sequence.manifest('2026-09-19T00:00:00Z'),
        'packedBytes': len(packed),
        'packedSha256': hashlib.sha256(packed).hexdigest(),
        'surfaceCellCounts': counts,
        'surfaceCellsSha256': surface_digest.hexdigest(),
    }
    (ROOT / 'fixtures/flame/expected.json').write_bytes((json.dumps(expected, indent=2) + '\n').encode('utf-8'))


if __name__ == '__main__':
    main()
